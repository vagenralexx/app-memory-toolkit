import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';

test('clientes simultâneos compartilham regras e memória, isolam projetos e retomam somente task explícita', { timeout: 30000 }, async t => {
  const root = await mkdtemp(join(process.env.APP_MEMORY_TEST_TMP ?? tmpdir(), 'app-memory-continuity-'));
  const app = join(root, 'app'); await mkdir(app);
  const source = join(app, 'session.js'); await writeFile(source, 'export function renewSession() { return true; }\n');
  const data = join(root, 'memory');
  async function connect(name) {
    const client = new Client({ name, version: '1' });
    await client.connect(new StdioClientTransport({ command: process.execPath, args: [resolve('src/cli.js'), 'serve', '--data', data], stderr: 'pipe' }));
    t.after(() => client.close());
    const call = async (name, args = {}, expectedError = false) => {
      const result = await client.callTool({ name, arguments: args });
      assert.equal(Boolean(result.isError), expectedError, JSON.stringify(result));
      return JSON.parse(result.content[0].text);
    };
    return { client, call };
  }
  const a = await connect('client-a');
  assert.match(a.client.getInstructions(), /Não carregar histórico|contexto|Fontes|projeto/);
  const project = await a.call('project_register', { name: 'Base', root: app, mode: 'existing' });
  const p = { project_id: project.id };
  const b = await connect('client-b');
  const rule = await a.call('project_rule_set', { ...p, title: 'Offline', content: 'Este app deve funcionar offline.' });
  const rules = await b.call('get_operating_rules', p);
  assert.ok(rules.base.some(row => row.id === 'lifecycle'));
  assert.equal(rules.project.results[0].id, rule.id);
  await a.call('project_index', p);
  const refs = await a.call('get_code_references', { ...p, topic: 'renewSession' });
  assert.equal(refs.results[0].state, 'SOURCE_CURRENT');
  assert.equal(refs.results[0].start_line, 1);
  await writeFile(source, '// changed\n');
  assert.equal((await b.call('get_code_references', { ...p, topic: 'renewSession' })).results[0].state, 'STALE');
  const fields = { ...p, title: 'Sessão', content: 'Corrigir sessão', acceptance: ['Teste de sessão passa'], priority: 'P0', recipe: 'session.js:1', method: 'Reproduzir e testar', target_paths: ['session.js'], consumers: ['Login'] };
  const task = await a.call('task_update', { ...fields, status: 'in_progress' });
  const task2 = await a.call('task_update', { ...fields, title: 'Outra tarefa', priority: 'P2', status: 'in_progress' });
  const cp = await a.call('task_checkpoint', { ...p, task_id: task.id, summary: 'Primeira unidade', next_action: 'Testar sessão' });
  const fromB = await b.call('task_resume', { ...p, task_id: task.id });
  assert.equal(fromB.checkpoint.id, cp.id);
  assert.equal((await b.call('task_resume', { ...p, task_id: task2.id })).checkpoint, null);
  await b.call('task_checkpoint', { ...p, task_id: task.id, summary: 'Atualização', next_action: 'Verificar', expected_revision: 1 });
  await a.call('task_checkpoint', { ...p, task_id: task.id, summary: 'Escrita obsoleta', next_action: 'Ignorar', expected_revision: 1 }, true);
  const h = await b.call('task_handoff', { ...p, task_id: task.id, goal: 'Corrigir sessão', status: 'in_progress', next_action: 'Testar', evidence: ['Hash observado'], open_issues: ['Teste pendente'] });
  assert.equal(h.immutable, true);
  assert.match(h.resume_prompt, new RegExp(task.id));
  const resumed = await a.call('task_resume', { ...p, task_id: task.id });
  assert.equal(resumed.current_state_id, h.id);
  const plainContext = await b.call('get_context', p);
  assert.ok(plainContext.results.every(row => !['task', 'checkpoint', 'handoff'].includes(row.kind)));
  const taskContext = await b.call('get_context', { ...p, task_id: task.id, budget: 10000 });
  assert.ok(taskContext.results.some(row => row.id === task.id));
  assert.ok(taskContext.results.some(row => row.id === h.id));
  assert.ok(taskContext.results.every(row => row.id !== task2.id));
  const projectList = await b.call('project_list', { limit: 1, offset: 0 });
  assert.equal(projectList.length, 1);
  assert.equal(projectList[0].answers, undefined);
  await a.call('handoff_write', { ...p, id: h.id, expected_revision: 1, title: 'Mutação', content: 'Não permitido' }, true);
  const memory = { ...p, namespace: 'patterns', key: 'session/retry', value: 'Renovar antes de tentar novamente.', evidence: ['session.js:1, relato do teste'], status: 'evidence_reported' };
  await a.call('memory_store', memory);
  assert.equal((await b.call('memory_retrieve', { ...p, namespace: 'patterns', key: 'session/retry' })).results.length, 1);
  assert.equal((await b.call('memory_search', { ...p, query: 'Renovar', namespace: 'patterns' })).results.length, 1);
  await b.call('memory_store', { ...memory, value: 'Atualização sem revisão' }, true);
  await b.call('memory_store', { ...memory, value: 'Atualização revisada', expected_revision: 1 });
  const otherApp = join(root, 'other'); await mkdir(otherApp);
  const other = await a.call('project_register', { name: 'Outro', root: otherApp, mode: 'existing' });
  await b.call('task_resume', { project_id: other.id, task_id: task.id }, true);
  assert.equal((await b.call('memory_retrieve', { project_id: other.id, namespace: 'patterns', key: 'session/retry' })).results.length, 0);
  const update = await a.call('task_update', { ...p, id: task.id, expected_revision: 1, title: 'Sessão', content: 'Concluída', acceptance: fields.acceptance, status: 'done', evidence: ['Teste demonstrativo passou'], acceptance_met: true });
  assert.equal(update.revision, 2);
  const detail = await a.call('resolve_reference', { ...p, id: task.id, mode: 'raw', budget: 5000 });
  assert.equal(JSON.parse(detail.results[0].content).priority, 'P0');
  assert.equal(JSON.parse(detail.results[0].content).recipe, 'session.js:1');
});
